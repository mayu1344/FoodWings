CREATE UNIQUE INDEX uq_one_accepted_assignment ON delivery_assignments(order_id) WHERE status = 'ACCEPTED';

CREATE TABLE partner_earnings (
  earning_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id     BIGINT       NOT NULL REFERENCES delivery_partners(partner_id),
  order_id       BIGINT       NOT NULL UNIQUE REFERENCES orders(order_id),
  base_pay       DECIMAL(8,2) NOT NULL,
  distance_pay   DECIMAL(8,2) NOT NULL DEFAULT 0,
  tip            DECIMAL(8,2) NOT NULL DEFAULT 0,
  payout_status  VARCHAR(20)  NOT NULL DEFAULT 'PENDING' CHECK (payout_status IN ('PENDING','PAID')),
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE restaurant_payouts (
  payout_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  BIGINT        NOT NULL REFERENCES restaurants(restaurant_id),
  order_id       BIGINT        NOT NULL UNIQUE REFERENCES orders(order_id),
  order_amount   DECIMAL(10,2) NOT NULL,
  commission     DECIMAL(10,2) NOT NULL,
  payout_amount  DECIMAL(10,2) NOT NULL,
  payout_status  VARCHAR(20)   NOT NULL DEFAULT 'PENDING' CHECK (payout_status IN ('PENDING','PAID')),
  created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- =====================================================================
-- F. PAYMENT GATEWAY
--    The full card number and CVV NEVER reach these tables.
--    The gateway (Razorpay / Stripe / etc.) collects them in its own SDK
--    and returns a TOKEN. We store only: token, card brand, last 4 digits,
--    expiry month/year - all allowed by PCI-DSS.
-- =====================================================================
CREATE TABLE payment_gateways (
  gateway_id    SMALLINT    PRIMARY KEY,
  code          VARCHAR(20) NOT NULL UNIQUE,       -- MOCKPAY, RAZORPAY, STRIPE
  display_name  VARCHAR(50) NOT NULL,
  supports_card BOOLEAN     NOT NULL DEFAULT TRUE,
  supports_upi  BOOLEAN     NOT NULL DEFAULT TRUE,
  is_active     BOOLEAN     NOT NULL DEFAULT FALSE,
  priority      SMALLINT    NOT NULL DEFAULT 10    -- lower = tried first
  -- API keys / secrets are NOT stored here. They live in environment variables / a secrets vault.
);

-- Cards / UPI IDs the customer chose to save ("Saved cards" screen).
CREATE TABLE saved_payment_methods (
  method_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            BIGINT      NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  gateway_id         SMALLINT    NOT NULL REFERENCES payment_gateways(gateway_id),
  method_type        VARCHAR(10) NOT NULL CHECK (method_type IN ('CARD','UPI')),
  gateway_token      VARCHAR(100) NOT NULL UNIQUE,  -- token from the gateway, useless outside it
  card_network       VARCHAR(20),                    -- VISA / MASTERCARD / RUPAY / AMEX
  card_last4         CHAR(4),                        -- only the last 4 digits, for display
  card_expiry_month  SMALLINT,
  card_expiry_year   SMALLINT,
  upi_vpa_masked     VARCHAR(60),                    -- e.g. ra****@okaxis
  is_default         BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_last4      CHECK (card_last4 IS NULL OR card_last4 ~ '^[0-9]{4}$'),
  CONSTRAINT chk_exp_month  CHECK (card_expiry_month IS NULL OR card_expiry_month BETWEEN 1 AND 12),
  CONSTRAINT chk_card_cols  CHECK (method_type <> 'CARD' OR (card_last4 IS NOT NULL AND card_network IS NOT NULL))
);

CREATE TABLE payments (
  payment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id            BIGINT        NOT NULL REFERENCES orders(order_id),
  user_id             BIGINT        NOT NULL REFERENCES users(user_id),
  gateway_id          SMALLINT      REFERENCES payment_gateways(gateway_id),   -- NULL for COD
  method_type         VARCHAR(10)   NOT NULL CHECK (method_type IN ('CARD','UPI','COD','WALLET')),
  saved_method_id     BIGINT        REFERENCES saved_payment_methods(method_id),
  card_network        VARCHAR(20),       -- copied for receipts ("VISA •••• 1111")
  card_last4          CHAR(4) CHECK (card_last4 IS NULL OR card_last4 ~ '^[0-9]{4}$'),
  amount              DECIMAL(10,2) NOT NULL CHECK (amount >= 0),
  currency            CHAR(3)       NOT NULL DEFAULT 'INR',
  status              VARCHAR(20)   NOT NULL DEFAULT 'CREATED'
                      CHECK (status IN ('CREATED','PENDING','AUTHORIZED','CAPTURED','FAILED',
                                        'REFUNDED','PARTIALLY_REFUNDED','COD_PENDING','COD_COLLECTED')),
  idempotency_key     VARCHAR(64)   NOT NULL UNIQUE,  -- stops double charging if the user taps twice
  gateway_order_ref   VARCHAR(100)  UNIQUE,           -- order id created at the gateway
  gateway_payment_ref VARCHAR(100)  UNIQUE,           -- payment id returned by the gateway
  failure_code        VARCHAR(50),
  failure_reason      VARCHAR(200),
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_order ON payments(order_id);

-- Every call we make to the gateway (authorize, capture, refund) = one row.
CREATE TABLE payment_transactions (
  txn_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id        BIGINT        NOT NULL REFERENCES payments(payment_id),
  txn_type          VARCHAR(20)   NOT NULL CHECK (txn_type IN ('CREATE_ORDER','AUTHORIZE','CAPTURE','REFUND','VOID')),
  amount            DECIMAL(10,2) NOT NULL,
  status            VARCHAR(20)   NOT NULL CHECK (status IN ('SUCCESS','FAILED','PENDING')),
  gateway_txn_ref   VARCHAR(100),
  gateway_response  JSONB         NOT NULL DEFAULT '{}'::jsonb,   -- SANITISED response (checked by trigger)
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_ptxn_payment ON payment_transactions(payment_id);

CREATE TABLE refunds (
  refund_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id         BIGINT        NOT NULL REFERENCES payments(payment_id),
  amount             DECIMAL(10,2) NOT NULL CHECK (amount > 0),
  reason             VARCHAR(200),
  status             VARCHAR(20)   NOT NULL DEFAULT 'INITIATED'
                     CHECK (status IN ('INITIATED','PROCESSED','FAILED')),
  gateway_refund_ref VARCHAR(100)  UNIQUE,
  initiated_by       BIGINT        REFERENCES users(user_id),
  created_at         TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Gateway calls us back (webhook) when a payment succeeds/fails.
CREATE TABLE payment_webhook_events (
  event_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gateway_id        SMALLINT     NOT NULL REFERENCES payment_gateways(gateway_id),
  gateway_event_id  VARCHAR(100) NOT NULL,          -- gateway's own event id
  event_type        VARCHAR(60)  NOT NULL,          -- payment.captured, payment.failed, refund.processed
  payment_id        BIGINT       REFERENCES payments(payment_id),
  signature_valid   BOOLEAN      NOT NULL,
  payload           JSONB        NOT NULL,          -- SANITISED payload (checked by trigger)
  received_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  processed_at      TIMESTAMPTZ,
  UNIQUE (gateway_id, gateway_event_id)             -- same webhook delivered twice = ignored
);

-- =====================================================================
-- updated_at triggers
-- =====================================================================
CREATE TRIGGER trg_users_upd       BEFORE UPDATE ON users       FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_restaurants_upd BEFORE UPDATE ON restaurants FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_menu_items_upd  BEFORE UPDATE ON menu_items  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_orders_upd      BEFORE UPDATE ON orders      FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_payments_upd    BEFORE UPDATE ON payments    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =====================================================================
-- Documentation stored inside the database itself
-- =====================================================================
COMMENT ON TABLE payments IS
  'One row per payment attempt. CVV/CVC and full card number are NEVER stored (PCI-DSS req. 3.3). Only gateway refs, brand and last 4 digits.';
COMMENT ON TABLE saved_payment_methods IS
  'Saved cards = gateway TOKEN + brand + last4 + expiry. No CVV, no full card number, ever.';
COMMENT ON COLUMN payment_transactions.gateway_response IS
  'Sanitised gateway response. A trigger rejects any JSON containing cvv/cvc/card_number keys or a full card number.';
COMMENT ON TABLE orders IS 'Hub table: links customer, restaurant, delivery partner, address and coupon.';
